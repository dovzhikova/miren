"use client";

import { useSyncExternalStore } from "react";
import { clearPhotos, forgetMemoryPhotos, prunePhotos } from "@/lib/photo-vault";
import { scanWorkspace, type Workspace } from "@/lib/scan-kind";
import { newState, newStoredState, restoreState, retainScans } from "@/lib/state";
import type { AppState, Scan } from "@/lib/types";

const STORAGE_KEY = "glowcheck.v2";
const LEGACY_KEY = "glowcheck.v1";
export const emptyState = newState();
let stored = newStoredState();

type Snapshot = {
  hydrated: boolean;
  state: AppState;
  workspace: Workspace;
};

const serverSnapshot: Snapshot = { hydrated: false, state: emptyState, workspace: "mock" };
let snapshot: Snapshot = serverSnapshot;
const listeners = new Set<() => void>();

function subscribe(listener: () => void) {
  if (listeners.size === 0 && typeof window !== "undefined") window.addEventListener("storage", receiveStorage);
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
    if (listeners.size === 0 && typeof window !== "undefined") window.removeEventListener("storage", receiveStorage);
  };
}

function receiveStorage(event: StorageEvent) {
  if (event.key !== STORAGE_KEY && event.key !== null) return;
  if (event.newValue === null) forgetMemoryPhotos();
  try { stored = restoreState(JSON.parse(event.newValue ?? "null")); } catch { stored = newStoredState(); }
  snapshot = { hydrated: true, state: stored.workspaces[stored.workspace], workspace: stored.workspace };
  listeners.forEach((listener) => listener());
}

function emit(next: AppState) {
  stored.workspaces[stored.workspace] = next;
  persist();
  snapshot = { hydrated: true, state: stored.workspaces[stored.workspace], workspace: stored.workspace };
  listeners.forEach((listener) => listener());
}

function persist() {
  if (typeof window === "undefined") return;
  const save = () => localStorage.setItem(STORAGE_KEY, JSON.stringify(stored));
  try {
    save();
    localStorage.removeItem(LEGACY_KEY);
  } catch {
    // Keep scores and API-quality blobs; thumbnails may be regenerated by a new scan.
    for (const workspace of ["mock", "live"] as const) {
      stored.workspaces[workspace] = { ...stored.workspaces[workspace], scans: stored.workspaces[workspace].scans.map((scan) => ({ ...scan, previewDataUrl: undefined })) };
    }
    try { save(); } catch { /* Scores remain available for this visit. */ }
  }
}

function ensureClient() {
  if (snapshot.hydrated || typeof window === "undefined") return;
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    const legacy = raw ? null : localStorage.getItem(LEGACY_KEY);
    stored = restoreState(JSON.parse(raw ?? legacy ?? "null"), Boolean(legacy));
  } catch { stored = newStoredState(); }
  snapshot = { hydrated: true, state: stored.workspaces[stored.workspace], workspace: stored.workspace };
}

export function mockHasScans(): boolean {
  ensureClient();
  return stored.workspaces.mock.scans.length > 0;
}

/** Drop a labeled demo baseline, follow-up, and mixed routine into an empty Demo workspace. */
export function installDemoStory(story: AppState) {
  ensureClient();
  stored.workspace = "mock";
  const current = stored.workspaces.mock;
  if (current.scans.length > 0) {
    emit(current);
    return;
  }
  emit({
    ...current,
    scans: story.scans,
    baselineId: story.baselineId,
    routine: story.routine,
  });
}

export function setWorkspace(workspace: Workspace) {
  ensureClient();
  stored.workspace = workspace;
  emit(stored.workspaces[workspace]);
}

/** First visit with a configured live server opens My scans. A saved choice wins. */
export function noteLiveDefault() {
  ensureClient();
  if (typeof window === "undefined") return;
  if (localStorage.getItem(STORAGE_KEY) || localStorage.getItem(LEGACY_KEY)) return;
  if (stored.workspace === "live") return;
  stored.workspace = "live";
  snapshot = { hydrated: true, state: stored.workspaces.live, workspace: "live" };
  listeners.forEach((listener) => listener());
}

export async function deleteAllData() {
  ensureClient();
  // Clear blobs first so a failed browser transaction is reported and retryable.
  await clearPhotos();
  await fetch("/api/config", { method: "DELETE" }).catch(() => {});
  localStorage.removeItem(STORAGE_KEY);
  localStorage.removeItem(LEGACY_KEY);
  localStorage.removeItem("glowcheck.look");
  stored = newStoredState();
  snapshot = { hydrated: true, state: stored.workspaces.mock, workspace: "mock" };
  listeners.forEach((listener) => listener());
}

export function toggleSaved(productId: string) {
  ensureClient();
  const ids = snapshot.state.savedProductIds;
  emit({ ...snapshot.state, savedProductIds: ids.includes(productId) ? ids.filter((id) => id !== productId) : [...ids, productId] });
}

function getSnapshot() {
  ensureClient();
  return snapshot;
}

export function addScan(scan: Scan) {
  ensureClient();
  const workspace = scanWorkspace(scan);
  const current = stored.workspaces[workspace];
  const normalized = { ...scan, mode: workspace, auth: workspace === "mock" ? "none" as const : scan.auth };
  stored.workspace = workspace;
  emit({ ...current, scans: retainScans(current, normalized), baselineId: current.baselineId ?? scan.id });
  const ids = Object.values(stored.workspaces).flatMap((state) => state.scans.map((item) => item.id));
  void prunePhotos(ids).catch(() => {});
}

export function setBaseline(scanId: string) {
  ensureClient();
  if (!snapshot.state.scans.some((scan) => scan.id === scanId)) return;
  emit({ ...snapshot.state, baselineId: scanId });
}

export function addToCart(productId: string) {
  ensureClient();
  if (snapshot.state.cart.some((line) => line.productId === productId)) return;
  emit({ ...snapshot.state, cart: [...snapshot.state.cart, { productId, qty: 1 }] });
}

export function removeFromCart(productId: string) {
  ensureClient();
  emit({ ...snapshot.state, cart: snapshot.state.cart.filter((line) => line.productId !== productId) });
}

export function setQty(productId: string, qty: number) {
  ensureClient();
  if (qty <= 0) {
    emit({ ...snapshot.state, cart: snapshot.state.cart.filter((line) => line.productId !== productId) });
    return;
  }
  emit({
    ...snapshot.state,
    cart: snapshot.state.cart.map((line) => (line.productId === productId ? { ...line, qty } : line)),
  });
}

export function startHabit(habitId: string) {
  ensureClient();
  if (snapshot.state.habitIds.includes(habitId)) return;
  emit({ ...snapshot.state, habitIds: [...snapshot.state.habitIds, habitId] });
}

export function stopHabit(habitId: string) {
  ensureClient();
  emit({ ...snapshot.state, habitIds: snapshot.state.habitIds.filter((id) => id !== habitId) });
}

export function toggleHabitCheck(habitId: string, day: string) {
  ensureClient();
  if (!/^\d{4}-\d{2}-\d{2}$/.test(day)) return;
  if (!snapshot.state.habitIds.includes(habitId)) return;
  const current = snapshot.state.habitChecks[habitId] ?? [];
  const next = current.includes(day) ? current.filter((item) => item !== day) : [...current, day];
  emit({ ...snapshot.state, habitChecks: { ...snapshot.state.habitChecks, [habitId]: next } });
}

export function toggleHabit(habitId: string) {
  ensureClient();
  const habitIds = snapshot.state.habitIds.includes(habitId)
    ? snapshot.state.habitIds.filter((id) => id !== habitId)
    : [...snapshot.state.habitIds, habitId];
  emit({ ...snapshot.state, habitIds });
}

export function removeFromRoutine(productId: string) {
  ensureClient();
  emit({ ...snapshot.state, routine: snapshot.state.routine.filter((item) => item.productId !== productId) });
}

export function checkout(productIds?: string[]) {
  ensureClient();
  const latest = snapshot.state.scans[0];
  if (!latest) return false;
  const chosen = new Set(productIds ?? snapshot.state.cart.map((line) => line.productId));
  const baselineScanId = latest.id;
  const routine = [...snapshot.state.routine];
  for (const productId of chosen) {
    if (!snapshot.state.cart.some((line) => line.productId === productId)) continue;
    if (routine.some((item) => item.productId === productId)) continue;
    routine.push({ productId, startedAt: new Date().toISOString(), baselineScanId });
  }
  emit({
    ...snapshot.state,
    routine,
    cart: snapshot.state.cart.filter((line) => !chosen.has(line.productId)),
  });
  return true;
}

export function useGlow() {
  const current = useSyncExternalStore(subscribe, getSnapshot, () => serverSnapshot);
  return {
    ready: current.hydrated,
    workspace: current.workspace,
    setWorkspace,
    toggleSaved,
    state: current.state,
    addScan,
    setBaseline,
    addToCart,
    removeFromCart,
    removeFromRoutine,
    toggleHabit,
    startHabit,
    stopHabit,
    toggleHabitCheck,
    checkout,
  };
}
